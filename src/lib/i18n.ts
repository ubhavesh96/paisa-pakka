const dict: Record<"hi" | "en", Record<StringKey, string>> = { en, hi };

/** Hinglish users see Hindi UI copy; the agent replies in Roman Hindi. */
export function uiLang(lang: Lang): "hi" | "en" {
  return lang === "en" ? "en" : "hi";
}

export function translate(lang: Lang, key: StringKey, vars?: Record<string, string | number>): string {
  let s = dict[uiLang(lang)][key] ?? en[key];
  if (vars) for (const [k, v] of Object.entries(vars)) s = s.replaceAll(`{${k}}`, String(v));
  return s;
}

export const speechLang = (lang: Lang) => (lang === "en" ? "en-IN" : "hi-IN");

export const fmtDate = (ts: number, lang: Lang) =>
  new Date(ts).toLocaleDateString(lang === "en" ? "en-IN" : "hi-IN", { day: "numeric", month: "short", year: "numeric" });

export const fmtTime = (ts: number, lang: Lang) =>
  new Date(ts).toLocaleTimeString(lang === "en" ? "en-IN" : "hi-IN", { hour: "numeric", minute: "2-digit" });

/** Indian digit grouping: 125000 -> 1,25,000 */
export const inr = (n: number) => Math.round(n).toLocaleString("en-IN");
